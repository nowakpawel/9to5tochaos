Renderer::Renderer() = default;

Renderer::~Renderer() {
    if (m_vao3D) glDeleteVertexArrays(1, &m_vao3D);
    if (m_vbo3D) glDeleteBuffers(1, &m_vbo3D);
    if (m_vaoHUD) glDeleteVertexArrays(1, &m_vaoHUD);
    if (m_vboHUD) glDeleteBuffers(1, &m_vboHUD);
    delete m_basic3D;
    delete m_hud2D;
}

void Renderer::init(int w, int h) {
    screenW = w;
    screenH = h;

    m_basic3D = new Shader(BASIC_VERT, BASIC_FRAG);
    m_hud2D   = new Shader(HUD_VERT, HUD_FRAG);

    // 3D VAO/VBO
    glGenVertexArrays(1, &m_vao3D);
    glGenBuffers(1, &m_vbo3D);
    glBindVertexArray(m_vao3D);
    glBindBuffer(GL_ARRAY_BUFFER, m_vbo3D);
    glBufferData(GL_ARRAY_BUFFER, 0, nullptr, GL_DYNAMIC_DRAW);
    glEnableVertexAttribArray(0);
    glVertexAttribPointer(0, 3, GL_FLOAT, GL_FALSE, 6*sizeof(float), (void*)0);
    glEnableVertexAttribArray(1);
    glVertexAttribPointer(1, 3, GL_FLOAT, GL_FALSE, 6*sizeof(float), (void*)(3*sizeof(float)));
    glBindVertexArray(0);

    // HUD VAO/VBO — Vertex2D: x,y,r,g,b,a
    glGenVertexArrays(1, &m_vaoHUD);
    glGenBuffers(1, &m_vboHUD);
    glBindVertexArray(m_vaoHUD);
    glBindBuffer(GL_ARRAY_BUFFER, m_vboHUD);
    glBufferData(GL_ARRAY_BUFFER, 0, nullptr, GL_DYNAMIC_DRAW);
    glEnableVertexAttribArray(0);
    glVertexAttribPointer(0, 2, GL_FLOAT, GL_FALSE, 6*sizeof(float), (void*)0);
    glEnableVertexAttribArray(1);
    glVertexAttribPointer(1, 4, GL_FLOAT, GL_FALSE, 6*sizeof(float), (void*)(2*sizeof(float)));
    glBindVertexArray(0);

    float aspect = static_cast<float>(w) / static_cast<float>(h);
    m_proj = glm::perspective(glm::radians(90.0f), aspect, 0.1f, 100.0f);
    m_hudProj = glm::ortho(0.0f, (float)w, (float)h, 0.0f, -1.0f, 1.0f);

    glEnable(GL_DEPTH_TEST);
}

