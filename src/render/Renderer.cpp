// Vertex shader for 3D geometry
static const char* BASIC_VERT = R"(
#version 330 core
layout(location=0) in vec3 aPos;
layout(location=1) in vec3 aColor;
uniform mat4 uModel;
uniform mat4 uView;
uniform mat4 uProjection;
out vec3 vColor;
void main(){
    gl_Position = uProjection * uView * uModel * vec4(aPos,1.0);
    vColor = aColor;
}
)";

static const char* BASIC_FRAG = R"(
#version 330 core
in vec3 vColor;
out vec4 fragColor;
uniform float uAlpha;
void main(){ fragColor = vec4(vColor, uAlpha); }
)";

static const char* HUD_VERT = R"(
#version 330 core
layout(location=0) in vec2 aPos;
layout(location=1) in vec4 aColor;
uniform mat4 uProjection;
out vec4 vColor;
void main(){
    gl_Position = uProjection * vec4(aPos, 0.0, 1.0);
    vColor = aColor;
}
)";

static const char* HUD_FRAG = R"(
#version 330 core
in vec4 vColor;
out vec4 fragColor;
void main(){ fragColor = vColor; }
)";

